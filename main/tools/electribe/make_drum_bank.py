"""Embed selected authentic the app drum WAVs as a C header.

Reads `assets/drums/*.wav` (extracted by extract_drums.py) and emits
`firmware/gen/electribe_drums.h` — const int16 PCM arrays used by the firmware's
drum engine. Only the samples flagged in `MAPPING` are embedded, to keep the image
small; the full 14-sound bank stays as reference assets.

Usage:
    python3 tools/electribe/make_drum_bank.py

MAPPING maps a part id -> input WAV file. The firmware indexes DRUM_BANK[0..4]
for KICK, SNARE, CLAP, CHH, OHH.
"""

import struct
import sys
import wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "assets" / "drums"
OUT = ROOT / "firmware" / "gen" / "electribe_drums.h"

# part id -> wav (from the extracted inventory; see assets/drums/inventory.json)
MAPPING = {
    "KICK": "drum_07_kick.wav",
    "SNARE": "drum_03_snare_tom.wav",
    "CLAP": "drum_10_percussion.wav",
    "CHH": "drum_00_snare_tom.wav",   # sharp short treble hit
    "OHH": "drum_04_hihat.wav",
}

MAX_16 = 32767


def load16(path: Path):
    w = wave.open(str(path))
    assert w.getnchannels() == 1, path
    n = w.getnframes()
    fr = w.readframes(n)
    # int16 little-endian (wave module gives LE), sample rate preserved at 44100
    samples = struct.unpack("<%dh" % n, fr)
    return samples


def main() -> int:
    if not SRC.exists():
        print("no assets/drums; run extract_drums.py first")
        return 1
    parts = list(MAPPING.keys())
    data = {}
    for part in parts:
        f = MAPPING[part]
        p = SRC / f
        if not p.exists():
            print("missing", p)
            return 1
        data[part] = load16(p)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* GENERATED by tools/electribe/make_drum_bank.py — do not edit by hand. */",
        "/* Authentic the source app drum one-shots, extracted from the .ipa's",
        " * drumdata.bin (DrumPCMROM) by extract_drums.py. Mono, 16-bit, 44100 Hz. */",
        "#ifndef ELECTRIBE_DRUMS_H",
        "#define ELECTRIBE_DRUMS_H",
        "#include <stdint.h>",
        f"#define N_DRUM_BANK {len(parts)}u",
        "/* part order: KICK(0) SNARE(1) CLAP(2) CHH(3) OHH(4) */",
    ]
    for part in parts:
        s = data[part]
        lines.append(f"static const int16_t DRUM_{part}[{len(s)}] = {{")
        for j in range(0, len(s), 12):
            lines.append("    " + ", ".join(str(v) for v in s[j:j + 12]) + ",")
        lines.append("};")
        lines.append("")
    lines += [
        "static const struct { uint16_t n; const int16_t *p; } DRUM_BANK[N_DRUM_BANK] = {",
    ]
    for part in parts:
        lines.append(f"    {{ (uint16_t)(sizeof DRUM_{part} / sizeof DRUM_{part}[0]), DRUM_{part} }},")
    lines += ["};", "#endif", ""]
    OUT.write_text("\n".join(lines))
    total = sum(len(data[p]) for p in parts)
    print(f"wrote {OUT} ({len(parts)} drums, {total} samples = {total*2} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
