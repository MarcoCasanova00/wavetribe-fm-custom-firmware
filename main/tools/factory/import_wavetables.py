#!/usr/bin/env python3
"""Extract 2048-sample single-cycle wavetable waves from supplied Absynth-style banks."""
import os, struct, sys

NTABLES = 48
WT_SIZE = 2048
HDR = 48

def extract(fn):
    d = open(fn, "rb").read()
    out = []
    i = 0
    while True:
        j = d.find(b"wave", i)
        if j < 0:
            break
        try:
            be = struct.unpack(">I", d[j+4:j+8])[0]
        except Exception:
            break
        if 4000 <= be <= 4200:
            payload = d[j+8:j+8+be]
            if len(payload) >= HDR + WT_SIZE*2:
                ln = payload[12] & 0xff
                name = payload[13:13+ln] if (1 <= ln <= 32) else b""
                name = name.split(b"\x00")[0].decode("ascii", "replace").strip() or "wave"
                pcm = struct.unpack("<%dh" % WT_SIZE, payload[HDR:HDR+WT_SIZE*2])
                out.append((name, pcm))
        i = j + 1
    return out

def main():
    bank_dir = sys.argv[1] if len(sys.argv) > 1 else "/home/maltomare/new absynth banks"
    out = sys.argv[2] if len(sys.argv) > 2 else None
    if out is None:
        root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        out = os.path.join(root, "firmware", "gen", "factory_wavetables.h")
    banks = sorted(f for f in os.listdir(bank_dir) if not f.endswith("Zone.Identifier"))
    waves = []
    for bank in banks:
        if len(waves) >= NTABLES:
            break
        try:
            items = extract(os.path.join(bank_dir, bank))
        except (OSError, FileNotFoundError):
            continue
        for name, pcm in items:
            if len(waves) >= NTABLES:
                break
            waves.append((bank, name, pcm))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("/* GENERATED by tools/factory/import_wavetables.py - do not edit by hand. */\n")
        f.write("#ifndef FACTORY_WAVETABLES_H\n#define FACTORY_WAVETABLES_H\n\n")
        f.write("#define WT_SIZE     2048u\n")
        f.write("#define WT_SHIFT   21u\n")
        f.write("#define WT_COUNT     %uu\n\n" % len(waves))
        for idx, (bank, name, _) in enumerate(waves):
            f.write("/* WT%02u: %s / %s */\n" % (idx, bank[:40], name[:28]))
        f.write("\nstatic const int16_t WT_DATA[WT_COUNT][WT_SIZE] = {")
        for idx, (bank, name, pcm) in enumerate(waves):
            f.write("\n  { ")
            for k, v in enumerate(pcm):
                if k and k % 16 == 0:
                    f.write("\n    ")
                f.write("%d, " % v)
            f.write("},")
        f.write("\n};\n\n#endif /* FACTORY_WAVETABLES_H */\n")
    print("wrote %s with %d waves from %d banks" % (out, len(waves), len(banks)))

if __name__ == "__main__":
    main()
