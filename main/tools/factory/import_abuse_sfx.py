#!/usr/bin/env python3
"""Emit the ABUSE drum kit header from Abuse (DOS) SFX.
Abuse ships 8-bit/11025 Hz mono WAV effects, so the 8-bit samples are widened
to 16-bit and resampled to 44100 Hz. Output: firmware/gen/abuse_drum_kit.h."""
import struct, wave
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "main" / "firmware" / "gen" / "abuse_drum_kit.h"
SFX = Path("/tmp/opencode/abuse/ABUSE/SFX")

PARTS = ("KICK", "SNARE", "CLAP", "CHH", "OHH")
FILES = {"KICK": "MGHIT02", "SNARE": "SHOTGN31", "CLAP": "DELOBJ01",
         "CHH": "SWISH01", "OHH": "LASRMIS2"}

def load16(path):
    w = wave.open(str(path)); n = w.getnframes(); fr = w.readframes(n)
    s = [(b - 128) * 256 for b in fr] if w.getsampwidth() == 1 \
        else list(struct.unpack("<%dh" % n, fr))
    if w.getframerate() != 44100:
        ratio = w.getframerate() / 44100.0; out, i = [], 0.0
        while i < len(s):
            out.append(s[int(i)]); i += ratio
        s = out
    return s[:20000]

def main():
    samps = {p: load16(SFX / (FILES[p] + ".WAV")) for p in PARTS}
    L = ["/* GENERATED by tools/factory/import_abuse_sfx.py - do not edit. */",
         "#ifndef ABUSE_DRUM_KIT_H", "#define ABUSE_DRUM_KIT_H",
         "#include <stdint.h>", ""]
    for part in PARTS:
        s = samps[part]
        L.append("static const int16_t ABUSE_%s[%d] = {" % (part, len(s)))
        for j in range(0, len(s), 12):
            L.append("    " + ", ".join(str(v) for v in s[j:j + 12]) + ",")
        L += ["};", ""]
    L.append("static const drum_smp_t ABUSE_KIT[5] = {")
    for part in PARTS:
        L.append("  { %du, ABUSE_%s }," % (len(samps[part]), part))
    L += ["};", "#endif /* ABUSE_DRUM_KIT_H */", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n")
    print("wrote %s" % OUT)

if __name__ == "__main__":
    main()
