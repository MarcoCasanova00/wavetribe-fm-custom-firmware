"""Import authentic authentic factory patterns into RIPTIDE.

Each pattern file (29,320 B) has, next to the name/author/genre header, a
per-part sequencer block: 8 parts × 64 steps of gate bytes at offset 0x7048, followed
by a 64-byte accent array at 0x7248 (validated across all 160 extracted patterns).

This tool picks a curated set of genre-matching factory patterns and writes
`firmware/gen/patterns.h` with their 8×64 gate grids so the firmware can
play authentic factory grooves (the drum rows). The tonal (synth) rows are left empty here —
the firmware supplies its own bass/chord/lead note lines.

Usage:
    python3 tools/factory/make_patterns.py PATH_TO_APP_BUNDLE
"""

import glob
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "firmware" / "gen" / "factory_patterns.h"

TRIG_OFF = 0x7048
ACC_OFF = 0x7248
N_STEPS = 64
N_PARTS = 8

# genre -> a representative factory " (by filename hash); we pick by scanning.
# The first pattern whose genre field matches a target genre is used.
TARGETS = [
    ("TECHNO", "Techno"),
    ("HOUSE", "House"),
    ("DUBSTEP", "Dubstep"),
    ("DANDB", "D&B"),
    ("ELECTRO", "Electro"),
    ("TECHNO2", "Techno"),
    ("HOUSE2", "House"),
    ("DUB", "Dubstep"),
]


def genre_of(b):
    return b[0x28:0x28 + 16].split(b"\0")[0].decode("latin1", "replace").strip()


def name_of(b):
    return b[0x08:0x08 + 12].split(b"\0")[0].decode("latin1", "replace").strip()


def load_patterns(bundle):
    patdir = bundle / "patterns" if bundle.is_dir() else bundle
    entries = []
    for f in sorted(glob.glob(str(patdir / "*"))):
        b = Path(f).read_bytes()
        if len(b) < ACC_OFF + 64:
            continue
        # validate the grid
        trig = b[TRIG_OFF:TRIG_OFF + N_PARTS * N_STEPS]
        acc = b[ACC_OFF:ACC_OFF + 64]
        if not all(x in (0, 1) for x in trig) or not all(x in (0, 1) for x in acc):
            continue
        entries.append((name_of(b), genre_of(b), trig, acc))
    return entries


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    entries = load_patterns(Path(sys.argv[1]))
    if not entries:
        print("no valid patterns found")
        return 1
    # choose one distinct pattern per target genre
    chosen = []
    used = set()
    for slot, (label, genre) in enumerate(TARGETS):
        pick = None
        # prefer a named pattern (not "Init", not "Template N") of that genre
        for name, g, trig, acc in entries:
            if g == genre and name and name != "Init" and not name.startswith("Template") and name not in used:
                pick = (name, g, trig, acc)
                break
        if pick is None:
            for name, g, trig, acc in entries:
                if g == genre and name and name not in used:
                    pick = (name, g, trig, acc)
                    break
        if pick is None:
            pick = entries[slot % len(entries)]
        name, g, trig, acc = pick
        used.add(name)
        chosen.append((label, name, g, trig, acc))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "/* GENERATED by tools/factory/make_patterns.py — do not edit by hand. */",
        "/* Authentic the source app factory gates, extracted from the .ipa pattern files.",
        " * 8 parts × 64 steps per demo slot (rows 0..7 = the drum grid). The synth rows",
        " * are supplied by the firmware. (c) 2011 vendor — see docs/PORT.md. */",
        "#ifndef FACTORY_PATTERNS_H",
        "#define FACTORY_PATTERNS_H",
        f"#define N_DEMO_PAT {len(chosen)}u",
        "struct demo_pat { const char *slot; const char *name; const char *genre;",
        "                  uint8_t gates[8][64]; };",
        "static const struct demo_pat DEMO_PAT[N_DEMO_PAT] = {",
    ]
    for label, name, genre, trig, acc in chosen:
        lines.append(f'    {{"{label}", "{name}", "{genre}", {{')
        for r in range(N_PARTS):
            row = trig[r * N_STEPS:(r + 1) * N_STEPS]
            lines.append("        {" + ",".join(str(x) for x in row) + "},")
        lines.append("    }},")
    lines += ["};", "#endif", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(chosen)} patterns)")
    for label, name, genre, *_ in chosen:
        print(f"  {label:9s} <- {name} ({genre})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
