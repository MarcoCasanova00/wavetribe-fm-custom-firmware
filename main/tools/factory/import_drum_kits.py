def load16(path):
    if str(path).endswith(".bin"):
        raw = open(path,"rb").read()
        return [(b - 128) * 256 for b in raw]
    w = wave.open(str(path))
    n = w.getnframes()
    fr = w.readframes(n)
    s = list(struct.unpack("<%dh" % n, fr))
    if w.getframerate() != 44100:
        ratio = w.getframerate() / 44100.0
        out=[]; i=0.0
        while i < len(s):
            out.append(s[int(i)]); i += ratio
        s = out
    if len(s) > 20000:
        s = s[:20000]
    return s

