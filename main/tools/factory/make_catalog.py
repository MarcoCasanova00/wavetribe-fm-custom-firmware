"""Import the the source app (.ipa) pattern catalog into RIPTIDE.

Reads the extracted app bundle's `patterns/` directory (each file is one 29,320-byte
the app pattern: name, author, genre at fixed offsets) and writes
firmware/gen/catalog.h with the preset names/authors/genres so the
firmware UI can show the authentic factory preset library.

Usage:
    python3 tools/extract/make_catalog.py PATH_TO_APP_BUNDLE

Example:
    mkdir -p /tmp/ipa && cd /tmp/ipa && unzip app_ios_4.2.ipa
    python3 tools/extract/make_catalog.py /tmp/ipa/Payload/AppBundle.app

The step (gate/note) data of the binary format is not decoded by this script; the
firmware ships hand-authored demo patterns for the headline genres. importing
the full binary pattern layout is tracked as a follow-up (see docs/PORT.md).
"""

import glob
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "firmware" / "gen" / "factory_catalog.h"

NAME_OFF, NAME_LEN = 0x08, 12
AUTH_OFF, AUTH_LEN = 0x18, 16
GENR_OFF, GENR_LEN = 0x28, 16


def cstr(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').encode("latin1", "replace").decode("latin1")


def read_pattern(path: Path):
    b = path.read_bytes()
    if len(b) < 0x40:
        return None

    def fld(off, n):
        return b[off:off + n].split(b"\0")[0].decode("latin1", "replace").strip()

    name = fld(NAME_OFF, NAME_LEN)
    author = fld(AUTH_OFF, AUTH_LEN)
    genre = fld(GENR_OFF, GENR_LEN)
    if not name:
        return None
    return name, author, genre


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    bundle = Path(sys.argv[1])
    patdir = bundle / "patterns" if bundle.is_dir() else bundle
    files = sorted(glob.glob(str(patdir / "*")))
    entries = []
    for f in files:
        r = read_pattern(Path(f))
        if r:
            entries.append(r)
    # de-duplicate by (name, author, genre), keep a stable order; cap the catalog
    seen, catalog = set(), []
    for e in entries:
        if e in seen:
            continue
        seen.add(e)
        catalog.append(e)
    catalog.sort(key=lambda e: (e[2].lower(), e[0].lower()))
    if not catalog:
        print("no patterns found in", patdir)
        return 1
    lines = [
        "/* GENERATED by tools/extract/make_catalog.py — do not edit by hand. */",
        "/* The the source app factory preset catalog (name, author, genre). */",
        "/* (c) 2011 vendor — metadata reproduced for interoperability/documentation under",
        " * the GPL-3.0 port's scoping; see docs/PORT.md. */",
        "#ifndef FACTORY_CATALOG_H",
        "#define FACTORY_CATALOG_H",
        f"#define N_CATALOG {len(catalog)}u",
        "struct catalog_entry { const char *name; const char *author; const char *genre; };",
        "static const struct catalog_entry CATALOG[N_CATALOG] = {",
    ]
    for name, author, genre in catalog:
        lines.append(
            f'    {{"{cstr(name)}", "{cstr(author)}", "{cstr(genre)}"}},'
        )
    lines += [
        "};",
        "#endif",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(catalog)} presets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
