#!/usr/bin/env python3
"""Synthesize a bold face from the existing FONT_S (Terminus 16) bitmaps.

The firmware's font format stores 4-bit alpha nibbles per pixel (0 = off).
A "bold" pass thickens each glyph horizontally: a pixel keeps the maximum
alpha of itself and its left/right neighbours.  Advances/widths/offsets are
unchanged, so swapping FONT_S -> FONT_B never changes layout metrics.

Reads firmware/gen/felucca_font.h, writes firmware/gen/felucca_font_bold.h.
"""
import os, re, sys

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.normpath(os.path.join(ROOT, "firmware/gen/felucca_font.h"))
DST = os.path.normpath(os.path.join(ROOT, "firmware/gen/felucca_font_bold.h"))

def parse_array(name, text):
    m = re.search(r"%s\[[^\]]*\]\s*=\s*\{(.*?)\};" % name, text, re.S)
    if not m:
        sys.exit("array not found: " + name)
    return [int(t, 0) for t in re.findall(r"0[xX][0-9A-Fa-f]+|\d+", m.group(1))]

text = open(SRC).read()

adv = parse_array("FONT_S_ADV", text)
bw  = parse_array("FONT_S_BW", text)
off  = parse_array("FONT_S_OFF", text)
data = parse_array("FONT_S_DATA", text)

ngly = len(off)
H = 16
assert len(adv) == ngly and len(bw) == ngly

newdata = []
for g in range(ngly):
    w = bw[g]
    bpr = (w + 1) // 2
    rows = []                      # rows[y][x] = nibble
    base = off[g]
    for y in range(H):
        row = []
        for x in range(w):
            b = data[base + y * bpr + x // 2]
            nib = (b >> 4) if (x & 1) == 0 else (b & 15)
            row.append(nib)
        rows.append(row)
    # horizontal dilation: max of self + neighbours
    for y in range(H):
        out = []
        for x in range(w):
            v = rows[y][x]
            if x > 0 and rows[y][x - 1] > v:
                v = rows[y][x - 1]
            if x + 1 < w and rows[y][x + 1] > v:
                v = rows[y][x + 1]
            out.append(v)
        # repack
        for x in range(0, w, 2):
            hi = out[x]
            lo = out[x + 1] if x + 1 < w else 0
            newdata.append((hi << 4) | lo)

with open(DST, "w") as f:
    f.write("/* GENERATED by tools/gen_font_bold.py - synthetic bold derived from\n")
    f.write(" * FONT_S (Terminus 16). Same metrics as FONT_S; only the glyph\n")
    f.write(" * bitmaps are thickened (horizontal dilation). */\n")
    f.write("#ifndef FELUCCA_FONT_BOLD_H\n#define FELUCCA_FONT_BOLD_H\n")
    f.write("#include <stdint.h>\n")
    f.write("static const uint8_t FONT_B_DATA[%d] = {\n" % len(newdata))
    for i in range(0, len(newdata), 16):
        f.write("    " + ", ".join("0x%02x" % v for v in newdata[i:i + 16]) + ",\n")
    f.write("};\n")
    def emit(name, arr, ctype="uint16_t"):
        f.write("static const %s %s[%d] = {\n" % (ctype, name, len(arr)))
        for i in range(0, len(arr), 16):
            f.write("    " + ", ".join(str(v) for v in arr[i:i + 16]) + ",\n")
        f.write("};\n")
    emit("FONT_B_OFF", off)
    emit("FONT_B_ADV", adv, "uint8_t")
    emit("FONT_B_BW", bw, "uint8_t")
    f.write("static const felucca_font_t FONT_B = { 16, 2, 32, 126, FONT_B_ADV, FONT_B_BW, FONT_B_OFF, FONT_B_DATA };\n")
    f.write("#endif /* FELUCCA_FONT_BOLD_H */\n")

print("wrote %s (%d bytes, %d glyphs)" % (DST, len(newdata), ngly))
